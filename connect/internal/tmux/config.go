package tmux

import (
	"bufio"
	"bytes"
	"fmt"
	"os"
	"os/exec"
	"os/user"
	"path/filepath"
	"regexp"
	"runtime"
	"strings"
)

// ConfigOptions are the inputs of the generated tmux config.
type ConfigOptions struct {
	// Shell is the login shell sessions start; empty leaves tmux's default.
	Shell string
	// DefaultTerminal is tmux-256color or screen-256color.
	DefaultTerminal string
	// Executable is this client's absolute path, used by the alert-bell
	// hook; empty or unsafe paths leave the hook out.
	Executable string
}

// safeConfigPath accepts absolute paths that need no escaping inside a
// double-quoted tmux string and a double-quoted sh word: no quotes,
// backslashes, `$`, backquotes, `#`, `;`, `{}`, `~` or control characters.
var safeConfigPath = regexp.MustCompile(`^/[A-Za-z0-9 ._+,:=@%/-]*$`)

// SafeConfigPath reports whether path may be written into the config.
func SafeConfigPath(path string) bool {
	return len(path) <= 1024 && safeConfigPath.MatchString(path) && !strings.Contains(path, "//")
}

// ConfigText renders the tmux config.
func ConfigText(opts ConfigOptions) string {
	var b strings.Builder
	b.WriteString("# Generated by aiqsa-connect for its own tmux server; it is rewritten on every start.\n")
	b.WriteString("set -s escape-time 10\n")
	b.WriteString("set -g history-limit 50000\n")
	b.WriteString("set -g window-size latest\n")
	b.WriteString("set -g mouse on\n")
	b.WriteString("set -g status off\n")
	b.WriteString("set -s extended-keys on\n")
	b.WriteString("set -g allow-rename off\n")
	terminal := opts.DefaultTerminal
	if terminal != "tmux-256color" {
		terminal = "screen-256color"
	}
	fmt.Fprintf(&b, "set -g default-terminal %s\n", terminal)
	b.WriteString("set -g bell-action any\n")
	if opts.Shell != "" && SafeConfigPath(opts.Shell) {
		fmt.Fprintf(&b, "set -g default-shell \"%s\"\n", opts.Shell)
	}
	if opts.Executable != "" && SafeConfigPath(opts.Executable) {
		// The hook string is single-quoted for the config parser; when it
		// runs, tmux parses `run-shell -b "<cmd>"` and sh runs <cmd>, where
		// the executable is a double-quoted word and the session name is
		// shell-quoted by the q: format modifier. Output never reaches a pane.
		fmt.Fprintf(&b, "set-hook -g alert-bell 'run-shell -b \"\\\"%s\\\" hook bell #{q:session_name} >/dev/null 2>&1\"'\n", opts.Executable)
	}
	return b.String()
}

// DetectTerminal returns tmux-256color when its terminfo entry exists, and
// screen-256color otherwise.
func DetectTerminal() string {
	if path, err := exec.LookPath("infocmp"); err == nil {
		if exec.Command(path, "tmux-256color").Run() == nil {
			return "tmux-256color"
		}
		return "screen-256color"
	}
	dirs := []string{"/usr/share/terminfo", "/lib/terminfo", "/etc/terminfo", "/usr/lib/terminfo"}
	if home, err := os.UserHomeDir(); err == nil {
		dirs = append([]string{filepath.Join(home, ".terminfo")}, dirs...)
	}
	for _, dir := range dirs {
		for _, sub := range []string{"t", "74"} {
			if _, err := os.Stat(filepath.Join(dir, sub, "tmux-256color")); err == nil {
				return "tmux-256color"
			}
		}
	}
	return "screen-256color"
}

// LoginShell returns $SHELL, else the passwd entry's shell, else /bin/sh.
func LoginShell() string {
	if shell := os.Getenv("SHELL"); usableShell(shell) {
		return shell
	}
	if shell := passwdShell(); usableShell(shell) {
		return shell
	}
	return "/bin/sh"
}

func usableShell(shell string) bool {
	if shell == "" || !filepath.IsAbs(shell) {
		return false
	}
	info, err := os.Stat(shell)
	return err == nil && info.Mode().IsRegular() && info.Mode().Perm()&0o111 != 0
}

func passwdShell() string {
	u, err := user.Current()
	if err != nil || u.Username == "" {
		return ""
	}
	if runtime.GOOS == "darwin" {
		out, err := exec.Command("dscl", ".", "-read", "/Users/"+u.Username, "UserShell").Output()
		if err != nil {
			return ""
		}
		_, shell, found := strings.Cut(strings.TrimSpace(string(out)), ":")
		if !found {
			return ""
		}
		return strings.TrimSpace(shell)
	}
	out, err := exec.Command("getent", "passwd", u.Username).Output()
	if err != nil {
		return ""
	}
	scanner := bufio.NewScanner(bytes.NewReader(out))
	if scanner.Scan() {
		fields := strings.Split(scanner.Text(), ":")
		if len(fields) >= 7 {
			return strings.TrimSpace(fields[6])
		}
	}
	return ""
}
