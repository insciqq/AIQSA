#!/usr/bin/env node

import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HTTP_METHODS = ["GET", "POST", "PUT", "PATCH", "DELETE", "HEAD", "OPTIONS"];
const OUTPUT_PATH = "agent_docs/generated/API_AND_SCHEMA.md";

function filesBelow(directory, predicate) {
  const files = [];
  if (!existsSync(directory)) return files;
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const target = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...filesBelow(target, predicate));
    else if (entry.isFile() && predicate(target)) files.push(target);
  }
  return files;
}

function exportedMethods(source) {
  const methods = new Set();
  const direct = new RegExp(
    `export\\s+(?:async\\s+)?(?:const|function)\\s+(${HTTP_METHODS.join("|")})\\b`,
    "g"
  );
  for (const match of source.matchAll(direct)) methods.add(match[1]);

  for (const block of source.matchAll(/export\s*\{([^}]*)\}/gs)) {
    for (const item of block[1].split(",")) {
      const alias = new RegExp(`(?:^|\\s)as\\s+(${HTTP_METHODS.join("|")})\\s*$`).exec(item);
      const directName = new RegExp(`^\\s*(${HTTP_METHODS.join("|")})\\s*$`).exec(item);
      const method = alias?.[1] ?? directName?.[1];
      if (method) methods.add(method);
    }
  }

  return HTTP_METHODS.filter((method) => methods.has(method));
}

function apiRows(root) {
  const apiRoot = path.join(root, "app", "api");
  return filesBelow(apiRoot, (filename) => path.basename(filename) === "route.ts")
    .map((filename) => {
      const relative = path.relative(path.join(root, "app"), filename).split(path.sep).join("/");
      const route = `/${relative.replace(/\/route\.ts$/u, "")}`;
      const methods = exportedMethods(readFileSync(filename, "utf8"));
      if (methods.length === 0) {
        throw new Error(`${path.relative(root, filename)} exports no recognized HTTP method`);
      }
      return { methods, route };
    })
    .sort((left, right) => left.route.localeCompare(right.route, "en"));
}

function schemaNames(root, kind) {
  const schemaPath = path.join(root, "prisma", "schema.prisma");
  if (!existsSync(schemaPath)) throw new Error("missing Prisma schema: prisma/schema.prisma");
  const source = readFileSync(schemaPath, "utf8");
  return [...source.matchAll(new RegExp(`^${kind}\\s+([A-Za-z][A-Za-z0-9_]*)\\s*\\{`, "gm"))]
    .map((match) => match[1])
    .sort((left, right) => left.localeCompare(right, "en"));
}

function bulletList(values) {
  return values.length > 0 ? values.map((value) => `- \`${value}\``).join("\n") : "- None";
}

export function buildGeneratedReference(root = process.cwd()) {
  root = path.resolve(root);
  const routes = apiRows(root);
  const models = schemaNames(root, "model");
  const enums = schemaNames(root, "enum");
  const routeTable = routes
    .map(({ methods, route }) => `| \`${route}\` | ${methods.map((method) => `\`${method}\``).join(", ")} |`)
    .join("\n");

  return `# GENERATED API AND SCHEMA REFERENCE

Generated by \`npm run docs:generate\` from \`app/api/**/route.ts\` and \`prisma/schema.prisma\`. Do not edit this file by hand. Dynamic route segments retain Next.js filesystem notation.

## API Routes (${routes.length})

| Route | Methods |
| --- | --- |
${routeTable}

## Prisma Models (${models.length})

${bulletList(models)}

## Prisma Enums (${enums.length})

${bulletList(enums)}
`;
}

export function writeGeneratedReference(root = process.cwd()) {
  root = path.resolve(root);
  const target = path.join(root, OUTPUT_PATH);
  mkdirSync(path.dirname(target), { recursive: true });
  writeFileSync(target, buildGeneratedReference(root));
  return target;
}

export function generatedReferenceErrors(root = process.cwd()) {
  root = path.resolve(root);
  const target = path.join(root, OUTPUT_PATH);
  if (!existsSync(target)) return [`missing generated reference: ${OUTPUT_PATH}`];
  let expected;
  try {
    expected = buildGeneratedReference(root);
  } catch (error) {
    return [`cannot generate ${OUTPUT_PATH}: ${error.message}`];
  }
  return readFileSync(target, "utf8") === expected
    ? []
    : [`${OUTPUT_PATH}: stale generated reference; run npm run docs:generate and review the diff`];
}

function parseArgs(argv) {
  let check = false;
  let root = process.cwd();
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === "--check") check = true;
    else if (arg === "--root" && argv[index + 1]) root = argv[++index];
    else throw new Error("usage: generate-doc-reference [--check] [--root <path>]");
  }
  return { check, root: path.resolve(root) };
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  try {
    const { check, root } = parseArgs(process.argv.slice(2));
    if (check) {
      const errors = generatedReferenceErrors(root);
      if (errors.length > 0) throw new Error(errors.join("\n"));
      console.log("generated documentation is current.");
    } else {
      console.log(`Generated ${path.relative(root, writeGeneratedReference(root))}.`);
    }
  } catch (error) {
    console.error(`generate-doc-reference: ${error.message}`);
    process.exitCode = 1;
  }
}
