export function memoryRetrievalLaneLimit(
  lane: MemoryRetrievalLane,
  aggregationRequested: boolean
): number {
  if (aggregationRequested && lane in MEMORY_RETRIEVAL_AGGREGATION_HISTORY_LANE_LIMITS) {
    return MEMORY_RETRIEVAL_AGGREGATION_HISTORY_LANE_LIMITS[
      lane as keyof typeof MEMORY_RETRIEVAL_AGGREGATION_HISTORY_LANE_LIMITS
    ];
  }
  return MEMORY_RETRIEVAL_LANE_LIMITS[lane];
}

